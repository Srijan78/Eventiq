/**
 * @fileoverview iCalendar (.ics) generation and Google Calendar link builder.
 */

/**
 * Escapes special characters for iCalendar text values.
 * @param {string} str
 * @returns {string}
 */
function escapeIcsText(str) {
  if (!str) {
    return '';
  }
  return str
    .replace(/\\/g, '\\\\')
    .replace(/;/g, '\\;')
    .replace(/,/g, '\\,')
    .replace(/\n/g, '\\n');
}

/**
 * Formats a date string 'YYYY-MM-DD' into iCalendar date format 'YYYYMMDD'.
 * @param {string} dateStr
 * @returns {string}
 */
function toIcsDate(dateStr) {
  return dateStr.replace(/-/g, '');
}

/**
 * Computes the next calendar day string in YYYYMMDD format for all-day DTEND.
 * @param {string} dateStr
 * @returns {string}
 */
function getNextDayIcsDate(dateStr) {
  const d = new Date(dateStr);
  d.setDate(d.getDate() + 1);
  const year = d.getFullYear();
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${year}${month}${day}`;
}

/**
 * Generates a valid RFC 5545 iCalendar string from a timeline milestone list.
 *
 * @param {Array<{ label: string, dueDate: string, tasks?: Array<{ title: string, detail?: string }> }>} timeline
 * @param {string} [eventName='Eventiq Plan']
 * @returns {string} Complete iCalendar formatted string
 */
export function generateIcs(timeline, eventName = 'Eventiq Plan') {
  const lines = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//Eventiq//GenAI Event Planner//EN',
    'CALSCALE:GREGORIAN',
    'METHOD:PUBLISH',
    `X-WR-CALNAME:${escapeIcsText(eventName)} Timeline`,
  ];

  const nowTimestamp = new Date().toISOString().replace(/[-:]/g, '').split('.')[0] + 'Z';

  for (let idx = 0; idx < timeline.length; idx++) {
    const m = timeline[idx];
    const startDate = toIcsDate(m.dueDate);
    const endDate = getNextDayIcsDate(m.dueDate);
    const summary = `${eventName}: ${m.label}`;

    let taskDesc = '';
    if (m.tasks && m.tasks.length > 0) {
      taskDesc = m.tasks
        .map((t, i) => `${i + 1}. ${t.title}${t.detail ? ` - ${t.detail}` : ''}`)
        .join('\n');
    }

    const description = `Milestone: ${m.label}\n\nTasks:\n${taskDesc || 'Complete scheduled milestone tasks.'}\n\nGenerated by Eventiq.`;

    lines.push(
      'BEGIN:VEVENT',
      `UID:${nowTimestamp}-${idx}@eventiq.local`,
      `DTSTAMP:${nowTimestamp}`,
      `DTSTART;VALUE=DATE:${startDate}`,
      `DTEND;VALUE=DATE:${endDate}`,
      `SUMMARY:${escapeIcsText(summary)}`,
      `DESCRIPTION:${escapeIcsText(description)}`,
      'STATUS:CONFIRMED',
      'TRANSP:TRANSPARENT',
      'END:VEVENT',
    );
  }

  lines.push('END:VCALENDAR');
  return lines.join('\r\n');
}

/**
 * Builds a direct "Add to Google Calendar" web link for a milestone.
 *
 * @param {{ label: string, dueDate: string, tasks?: Array<{ title: string, detail?: string }> }} milestone
 * @param {string} [eventName='Eventiq Plan']
 * @returns {string} URL string
 */
export function googleCalendarUrl(milestone, eventName = 'Eventiq Plan') {
  const startDate = toIcsDate(milestone.dueDate);
  const endDate = getNextDayIcsDate(milestone.dueDate);
  const text = encodeURIComponent(`${eventName}: ${milestone.label}`);

  let taskDesc = '';
  if (milestone.tasks && milestone.tasks.length > 0) {
    taskDesc = milestone.tasks
      .map((t, i) => `${i + 1}. ${t.title}${t.detail ? ` - ${t.detail}` : ''}`)
      .join('\n');
  }
  const details = encodeURIComponent(
    `Milestone: ${milestone.label}\n\nTasks:\n${taskDesc || 'Review checklist'}\n\nGenerated by Eventiq.`,
  );

  return `https://calendar.google.com/calendar/render?action=TEMPLATE&text=${text}&dates=${startDate}/${endDate}&details=${details}`;
}

